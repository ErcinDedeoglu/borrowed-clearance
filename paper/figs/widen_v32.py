"""v3.2: redraw the three TikZ diagrams that were narrower than the 6.5in text width (fig_design_v31 6.414in,
fig_threat 6.262in, fig_traj_schematic 5.945in) at 6.500in. Reads tikz/v31/<name>.tex, changes only horizontal
spacing (no font sizes, no labels, no content), writes tikz/v32/<name>.tex and v32/<name>.pdf.
Run from paper/figs (tectonic on PATH or $TECTONIC):   python3 widen_v32.py"""
import os, subprocess, re
HERE = os.path.dirname(os.path.abspath(__file__))
SRC, TZ, OUT = (os.path.join(HERE, "tikz", "v31"), os.path.join(HERE, "tikz", "v32"), os.path.join(HERE, "v32"))
TECTONIC = os.environ.get("TECTONIC", "tectonic")
TARGET = 6.5


def sub1(t, a, b):
    assert t.count(a) == 1, a
    return t.replace(a, b)


def design(p):   # grid unit 10mm -> p mm (columns wider; text unchanged)
    t = open(os.path.join(SRC, "fig_design_v31.tex")).read()
    t = sub1(t, "[x=10mm,y=6.5mm]", f"[x={p:.3f}mm,y=6.5mm]")
    return t


def threat(p):   # gaps between columns 0.7cm -> 0.7+p cm, channel boxes 5.3cm -> 5.3+p, bottom box 15.4 -> 15.4+3p
    t = open(os.path.join(SRC, "fig_threat.tex")).read()
    t = sub1(t, "right=0.7cm of svc", f"right={0.7 + p:.3f}cm of svc")
    t = sub1(t, "right=0.7cm of c1", f"right={0.7 + p:.3f}cm of c1")
    t = sub1(t, "text width=5.3cm", f"text width={5.3 + p:.3f}cm")
    t = sub1(t, "text width=15.4cm", f"text width={15.4 + 3 * p:.3f}cm")
    # registry note: set below the dashed registry line so it no longer crosses the trust-boundary frame
    t = sub1(t, "anchor=south west] at ([yshift=-0.55cm,xshift=0.1cm]reg.south)", "anchor=north west] at ([yshift=-0.6cm,xshift=0.1cm]reg.south)")
    return t


def traj(p):     # gaps between steps 0.35cm -> 0.35+p cm, end column 12.1cm -> 12.1+3p cm
    t = open(os.path.join(SRC, "fig_traj_schematic.tex")).read()
    t = t.replace("right=0.35cm of", f"right={0.35 + p:.3f}cm of")
    n = len(re.findall(r"at \(12\.1,", t)); assert n == 4
    t = t.replace("at (12.1,", f"at ({12.1 + 3 * p:.3f},")
    return t


def build(name, text):
    t = text.replace("generated by make_figs_v31.py", "generated by make_figs_v31.py, widened by widen_v32.py").replace(
        "generated by make_exhibits_v31.py", "generated by make_exhibits_v31.py, widened by widen_v32.py")
    open(os.path.join(TZ, name + ".tex"), "w").write(t)
    subprocess.run([TECTONIC, "-X", "compile", "--outdir", OUT, name + ".tex"], cwd=TZ, check=True, capture_output=True)
    o = subprocess.run(["pdfinfo", os.path.join(OUT, name + ".pdf")], capture_output=True, text=True).stdout
    w = float(re.search(r"Page size:\s+([\d.]+)", o).group(1)) / 72
    return w


def fit(name, f, lo, hi):
    for _ in range(30):
        mid = (lo + hi) / 2
        w = build(name, f(mid))
        if abs(w - TARGET) <= 0.003:
            break
        lo, hi = (mid, hi) if w < TARGET else (lo, mid)
    print(f"{name}: param={mid:.4f} width={w:.4f}in")


if __name__ == "__main__":
    fit("fig_design_v31", design, 10.0, 12.0)
    fit("fig_threat", threat, 0.0, 0.6)
    fit("fig_traj_schematic", traj, 0.0, 0.8)
