import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "v31")
S = json.load(open(os.path.join(OUT, "stats_v3.json")))
X = json.load(open(os.path.join(OUT, "exhibits_v3.json")))
PPATH = os.path.join(OUT, "positioning_v31.json")
P = json.load(open(PPATH)) if os.path.exists(PPATH) else None
MODELS = ("Qwen2.5-0.5B-Instruct", "Qwen2.5-1.5B-Instruct", "SmolLM2-1.7B-Instruct", "Qwen2.5-3B-Instruct")
SHORT = {"Qwen2.5-0.5B-Instruct": "Qwen2.5-0.5B", "Qwen2.5-1.5B-Instruct": "Qwen2.5-1.5B",
         "SmolLM2-1.7B-Instruct": "SmolLM2-1.7B", "Qwen2.5-3B-Instruct": "Qwen2.5-3B (bf16)"}
AL = {"A0_none": "A0", "A1_prompt_rule": "A1", "A2_code_verifier": "A2", "A3_structured_status": "A3"}
PATTERNS = ("trust_by_position", "approvals_that_float", "content_as_authority")


def esc(s):
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")


def pfmt(p):
    if p is None: return "--"
    if p >= 0.01: return f"{p:.2g}" if p < 0.1 else f"{p:.2f}".rstrip("0").rstrip(".") if p < 1 else "1"
    m, e = f"{p:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"


def w(name, s):
    # every tabular is wrapped in \fitbox (defined in main.tex): shrinks to \linewidth only when wider
    s = s.replace(r"\begin{tabular}", r"\fitbox{\begin{tabular}").replace(r"\end{tabular}", r"\end{tabular}}")
    open(os.path.join(OUT, name), "w").write("% generated by make_tabs_v31.py -- do not edit\n" + s)
    print("wrote", name)


def tests():
    L = [r"\begin{tabular}{@{}llrrrrrr@{}}\toprule",
         r"model & $Y$ vs $X$ & pairs & $b$ (only $X$) & $c$ (only $Y$) & $p$ exact & $p$ Holm & $Y-X$, pp [95\% bootstrap] \\ \midrule"]
    for m in MODELS:
        rows = [r for r in S["mcnemar"] if r["model"] == m]
        for i, r in enumerate(rows):
            L.append((SHORT[m] if i == 0 else "") + f" & {AL[r['second']]} vs {AL[r['first']]} & {r['pairs']} & {r['b_first_only']} & {r['c_second_only']} & "
                     + (r"-- & -- & n/a (no discordant pairs) \\" if r['b_first_only'] + r['c_second_only'] == 0 else
                     f"{pfmt(r['p_exact'])} & {pfmt(r['p_holm'])} & ${r['diff_pp']:+.1f}$ [${r['boot_lo']:+.1f}$, ${r['boot_hi']:+.1f}$] \\\\"))
        L.append(r"\addlinespace")
    L[-1] = r"\bottomrule\end{tabular}"
    a = "\n".join(L)
    C = [r"\begin{tabular}{@{}lllll@{}}\toprule",
         r"model & wording condition (8) & option order (W1--W3) & clearance variant (8) & channel (3) \\ \midrule"]
    for m in MODELS:
        c = S["cramer"][m]; cells = []
        for k in ("condition", "order_W1_W3", "variant", "channel"):
            v = c[k]
            cells.append("n/a (no unsafe execution)" if v["V"] is None else f"{v['V']:.2f} ($p$ {pfmt(v['p'])})")
        C.append(SHORT[m] + " & " + " & ".join(cells) + r" \\")
    C.append(r"\bottomrule\end{tabular}")
    w("tab_tests.tex", r"\small\setlength{\tabcolsep}{4pt}" + "\n(a) Exact McNemar tests on paired non-valid scenarios\\par\\smallskip\n" + a +
      "\n\n\\medskip (b) Cram\\'er's $V$ of unsafe execution with each design factor, A0, non-valid episodes ($n=384$; order: $n=288$)\\par\\smallskip\n" + "\n".join(C) + "\n")


def taxonomy():
    arms = ("A0_none", "A1_prompt_rule", "A3_structured_status")
    rules = [("F1", "trust without checking", r"first step is \texttt{execute\_transfer}", "nonvalid"),
             ("F2", "verify-then-ignore", r"own \texttt{verify\_clearance} returns \texttt{INVALID}, later \texttt{execute\_transfer}", "nonvalid"),
             ("F3", "stall", "no terminal action within three steps", "all"),
             ("F4", "format failure", r"no valid tool call (unknown tool name or prose)", "all"),
             ("F5", "over-caution", r"halt on a valid clearance (F5b: after \texttt{VALID})", "valid")]
    head = " & ".join(r"\multicolumn{3}{c}{" + SHORT[m] + "}" for m in MODELS)
    sub = " & ".join("A0 & A1 & A3" for _ in MODELS)
    cm = "".join(f"\\cmidrule(lr){{{4 + 3 * i}-{6 + 3 * i}}}" for i in range(4))
    L = [r"\begin{tabular}{@{}llr" + "rrr" * 4 + r"@{}}\toprule",
         r" & mode & $n$ & " + head + r" \\" + cm, r" & & & " + sub + r" \\ \midrule"]
    for code, name, rule, den in rules:
        n = {"nonvalid": 384, "all": 432, "valid": 48}[den]
        vals = []
        for m in MODELS:
            for a in arms:
                t = S["taxonomy"][f"{m}|{a}"]
                assert t["n_nonvalid"] == 384 and t["n_all"] == 432 and t["n_valid"] == 48
                vals.append(str(t[code]) + (f" ({t['F5b']})" if code == "F5" else ""))
        L.append(f"{code} & {name} & {n} & " + " & ".join(vals) + r" \\")
    L.append(r"\bottomrule\end{tabular}")
    R = [r"\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{0.42\textwidth}>{\raggedright\arraybackslash}p{0.46\textwidth}@{}}\toprule", r"mode & rule over the logged tool sequence & first example in model and grid order (\texttt{episode\_id}; verbatim model output) \\ \midrule"]
    for code, name, rule, den in rules:
        e = S["taxonomy_examples"][code]
        txt = " $\\to$ ".join(r"\texttt{" + esc(s["text"]).replace("{", r"\{").replace("}", r"\}") + "}" for s in e["steps"][:2])
        R.append(f"{code} & {rule} & {SHORT[e['model']]}, \\texttt{{{esc(e['episode_id']).replace('|', '|\\allowbreak{}')}}}: {txt} \\\\")
    R.append(r"\bottomrule\end{tabular}")
    w("tab_taxonomy.tex", r"\small\setlength{\tabcolsep}{3.2pt}" + "\n" + "\n".join(L) + "\n")
    w("tab_taxexamples.tex", "{\\footnotesize\\setlength{\\tabcolsep}{3pt}\n" + "\n".join(R) + "}\n")


def repro():
    M = S["manifests"]; I = S["integrity_per_model"]; D = S["a0a2"]
    L = [r"\begin{tabular}{@{}lllll@{}}\toprule", " & " + " & ".join(SHORT[m] for m in MODELS) + r" \\ \midrule"]
    def row(label, f): L.append(label + " & " + " & ".join(f(m) for m in MODELS) + r" \\")
    row("Hugging Face id", lambda m: r"\texttt{\scriptsize " + esc(M[m]["model"]) + "}")
    row("dtype", lambda m: M[m]["dtype"])
    row("decoding", lambda m: "greedy" if M[m]["decoding"].startswith("greedy") else esc(M[m]["decoding"]))
    row("max new tokens", lambda m: str(M[m]["max_new_tokens"]))
    row("base seed / draws", lambda m: f"{M[m]['base_seed']} / {M[m]['draws']}")
    row("episodes (unique ids)", lambda m: f"{I[m]['rows']:,} ({I[m]['unique_ids']:,})")
    row("replayed identically", lambda m: f"{I[m]['replay_identical']:,}/{I[m]['rows']:,}")
    row(r"wall clock, h\textsuperscript{a}", lambda m: f"{M[m]['wall_seconds'] / 3600:.1f}")
    row("A0/A2 identical-input divergence", lambda m: f"{D[m]['divergent']}/{D[m]['pairs']}")
    row(r"\texttt{episodes.jsonl} SHA-256 (first 16)", lambda m: r"\texttt{\scriptsize " + I[m]["episodes_sha256"][:16] + "}")
    L.append(r"\midrule")
    m0 = MODELS[0]
    for m in MODELS:
        for k in ("code_sha256", "system_prompts_sha256", "python", "followup_order"):
            assert M[m][k] == M[m0][k], (m, k)
        assert M[m]["versions"] == M[m0]["versions"]
    L.append(r"harness code SHA-256 & \multicolumn{4}{l}{\texttt{\scriptsize " + M[m0]["code_sha256"] + "}} \\\\")
    L.append(r"system prompts SHA-256 & \multicolumn{4}{l}{\texttt{\scriptsize " + M[m0]["system_prompts_sha256"] + "}} \\\\")
    v = M[m0]["versions"]
    L.append(r"software & \multicolumn{4}{l}{Python " + M[m0]["python"] + f", torch {esc(v['torch'])}, transformers {v['transformers']}, cryptography {v['cryptography']}" + r"} \\")
    L.append(r"\bottomrule\end{tabular}")
    w("tab_repro.tex", r"\small\setlength{\tabcolsep}{4pt}" + "\n" + "\n".join(L) + "\n")


def channel():
    arms = ("A0_none", "A1_prompt_rule", "A3_structured_status")
    L = [r"\begin{tabular}{@{}ll" + "r" * 3 + r"@{}}\toprule", r"model & arm & trust by position & approvals that float & content as authority \\ \midrule"]
    for m in MODELS:
        for i, a in enumerate(arms):
            c = S["channel"][f"{m}|{a}"]
            L.append((SHORT[m] if i == 0 else "") + f" & {AL[a]} & " + " & ".join(
                f"{c[p]['k']}/{c[p]['n']} ({c[p]['pct']:.0f}\\%, [{c[p]['lo']:.0f}, {c[p]['hi']:.0f}])" for p in PATTERNS) + r" \\")
        L.append(r"\addlinespace")
    L[-1] = r"\bottomrule\end{tabular}"
    w("tab_channel.tex", r"\small\setlength{\tabcolsep}{4pt}" + "\n" + "\n".join(L) + "\n")


def positioning():
    cols = list(P["columns"].keys())
    mark = {"Y": r"\checkmark", "-": "--", "?": "?"}
    L = [r"\begin{tabular}{@{}l" + "c" * len(cols) + r"@{}}\toprule", "evaluation & " + " & ".join(c for c in cols) + r" \\ \midrule"]
    for r in P["rows"]:
        name = esc(r["name"]) + (f"~\\cite{{{r['key']}}}" if r["key"] else "")
        L.append(name + " & " + " & ".join(mark[r["cells"][c]] for c in cols) + r" \\")
    L.append(r"\bottomrule\end{tabular}")
    leg = "; ".join(f"{c}: {esc(t)}" for c, t in P["columns"].items())
    w("tab_positioning.tex", r"\small\setlength{\tabcolsep}{5pt}" + "\n" + "\n".join(L) + "\n\n\\smallskip{\\footnotesize " + leg + ".}\n")


def relabel_v1():
    # v1 generated tables (figs/tab_main.tex by make_figs.py, figs/tab_pilot.tex by make_figs.py,
    # figs/tab_percond.tex by make_tab_percond.py): copied to v31/ with only the 3B row label changed to "(bf16)"
    for f in ("tab_main.tex", "tab_percond.tex", "tab_pilot.tex"):
        t = open(os.path.join(HERE, f)).read()
        open(os.path.join(OUT, f), "w").write(t.replace("Qwen2.5-3B &", "Qwen2.5-3B (bf16) &"))
        print("wrote", f)


if __name__ == "__main__":
    relabel_v1(); tests(); taxonomy(); repro(); channel()
