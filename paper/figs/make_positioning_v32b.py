r"""v3.2b related-work comparison (Table 1): v31/positioning_v31.json plus the v3.2, v3.2a and v3.2b changes, written to
v32b/positioning_v32b.json (shipped with the arXiv source as anc/positioning_v32b.json) and v32b/tab_positioning.tex.
In this release v31/positioning_v31.json is not included (it is held with the paper's internal records). Without it the script
reads v32b/positioning_v32b.json, the evidence record it would write, and rebuilds only v32b/tab_positioning.tex from it.
Changes: This work P5 (v3.2a), P7 and P8 -> partial ("P", printed (\checkmark)) with the reason per cell; FinVault marked as
withdrawn by its authors (arXiv v2, 30 Jul 2026), url pinned to v1; v3.2b: the retrieval note in "opened" gives the
retrieval date (2026-10-31, as recorded in v31/positioning_v31.json); table unchanged.
The closing legend sentences (partial cells of this work, FinVault note) are read from v32b/tab_positioning_notes.tex.
Run from paper/figs:   python3 make_positioning_v32b.py"""
import json, os, copy, re
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "v31", "positioning_v31.json")
FULL = os.path.exists(SRC)
P = json.load(open(SRC)) if FULL else None
NOTES = open(os.path.join(HERE, "v32b", "tab_positioning_notes.tex")).read().strip()
OUT = os.path.join(HERE, "v32b")
X5 = NOTES
m = re.match(r"This work, \(\\checkmark\): (P5 .*?); (P7 .*?); (P8 .*?)\. (\$\^\{\\dagger\}\$FinVault: .*)$", X5, re.S)
assert m, X5
P5, P7, P8, FV = m.group(1), m.group(2), m.group(3), m.group(4)


def plain(s):
    return s.replace(r"\arm{A2}", "A2").replace(r"$^{\dagger}$", "")


if FULL:
    # the first clause of "opened" (retrieval time and source) is restated with its date; the rest is kept as recorded
    STAMP = "2026-10-31 12:44-12:47 Asia/Dubai (UTC+4), arXiv abs/HTML pages "
    first, rest = P["opened"].split("; ", 1)
    assert first.startswith(STAMP), P["opened"]
    NEW = STAMP + "retrieved from the live arXiv records on 2026-10-31"
    Q = copy.deepcopy(P)
    Q["opened"] = NEW + "; " + rest + "; v3.2: FinVault v1 and its v2 withdrawal notice re-opened on arXiv 2026-11-01 00:29 Asia/Dubai (UTC+4); v3.2a: This work P5 set to partial (forged-signature and unregistered-key rejection unit-tested only, not run as an episode variant)"
    Q["legend"]["P"] = "holds only in part; the reason is given in the row's evidence"
    for r in Q["rows"]:
        if r["name"] == "FinVault":
            r["url"] = "https://arxiv.org/abs/2601.07853v1"
            r["status"] = plain(FV)
        if r["name"] == "This work":
            r["cells"]["P5"] = "P"; r["cells"]["P7"] = "P"; r["cells"]["P8"] = "P"
            r["evidence"]["P5"] = plain(P5); r["evidence"]["P7"] = plain(P7); r["evidence"]["P8"] = plain(P8)
    json.dump(Q, open(os.path.join(OUT, "positioning_v32b.json"), "w"), indent=1, ensure_ascii=True)
else:
    Q = json.load(open(os.path.join(OUT, "positioning_v32b.json")))


def esc(s):
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")


cols = list(Q["columns"].keys())
mark = {"Y": r"\checkmark", "P": r"(\checkmark)", "-": "--", "?": "?"}
L = [r"\begin{tabular}{@{}l" + "c" * len(cols) + r"@{}}\toprule", "evaluation & " + " & ".join(cols) + r" \\ \midrule"]
for r in Q["rows"]:
    name = esc(r["name"]) + (r"$^{\dagger}$" if "status" in r else "") + (f"~\\cite{{{r['key']}}}" if r["key"] else "")
    L.append(name + " & " + " & ".join(mark[r["cells"][c]] for c in cols) + r" \\")
L.append(r"\bottomrule\end{tabular}")
leg = "; ".join(f"{c}: {esc(t)}" for c, t in Q["columns"].items())
s = r"\small\setlength{\tabcolsep}{5pt}" + "\n" + "\n".join(L) + "\n\n\\smallskip{\\footnotesize " + leg + ". " + X5 + "}\n"
s = s.replace(r"\begin{tabular}", r"\fitbox{\begin{tabular}").replace(r"\end{tabular}", r"\end{tabular}}")
open(os.path.join(OUT, "tab_positioning.tex"), "w").write("% generated by make_positioning_v32b.py -- do not edit\n" + s)
print("wrote v32b/positioning_v32b.json, v32b/tab_positioning.tex" if FULL else "read v32b/positioning_v32b.json (v31/positioning_v31.json not present); wrote v32b/tab_positioning.tex")
