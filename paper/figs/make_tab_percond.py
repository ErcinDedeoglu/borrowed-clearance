"""Writes tab_percond.tex (Appendix E) from section S8 of runs/main/analysis/factorial-report.md.
Cells are copied verbatim from the report (k/n = p% [Wilson 95% CI]); do not edit the output by hand."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
REP = os.path.join(HERE, "..", "..", "runs", "main", "analysis", "factorial-report.md")
ORDER = ("Qwen2.5-0.5B-Instruct", "Qwen2.5-1.5B-Instruct", "SmolLM2-1.7B-Instruct", "Qwen2.5-3B-Instruct")
WL = {"W1_list": "W1 list", "W2_question": "W2 question", "W3_options": "W3 options", "W4_next": "W4 next", "W5_continue": "W5 continue"}
OL = {"execute_first": "EF", "halt_first": "HF", "na": "--"}
txt = open(REP).read()
blocks = {}
for part in txt.split("\n# Model: ")[0:]:
    m = re.match(r"(?:# Model: )?\S+/(\S+) ", part)
    if not m: continue
    s8 = part.split("## S8 per-condition table")[1]
    rows = [l for l in s8.splitlines() if l.startswith("| W")]
    blocks[m.group(1)] = rows
cell = lambda c: c.strip().replace("%", r"\%").replace(" = ", " = ")
L = ["% generated by paper/figs/make_tab_percond.py from runs/main/analysis/factorial-report.md (S8) -- do not edit by hand",
     r"\begin{tabular}{@{}lll llll@{}}", r"\toprule",
     r"Model & Wording & Order & A0 none & A1 prompt rule & A2 code gate* & A3 structured status \\", r"\midrule"]
for mi, mname in enumerate(ORDER):
    assert len(blocks[mname]) == 8, mname
    for i, r in enumerate(blocks[mname]):
        c = [x.strip() for x in r.strip("|").split("|")]
        w, o = [x.strip() for x in c[0].split("/")]
        L.append(f"{mname.replace('-Instruct','') if i == 0 else ''} & {WL[w]} & {OL[o]} & " + " & ".join(cell(x) for x in c[1:5]) + r" \\")
    L.append(r"\midrule" if mi < len(ORDER) - 1 else r"\bottomrule")
L.append(r"\end{tabular}")
open(os.path.join(HERE, "tab_percond.tex"), "w").write("\n".join(L) + "\n")
print("wrote tab_percond.tex", {k: len(v) for k, v in blocks.items()})
