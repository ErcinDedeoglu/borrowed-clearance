r"""v3.3 paired-tests table (tab_tests.tex), made only from v31/stats_v3.json (stats_v3.py over runs/main/). No number is typed here.
Same rows as make_tabs_v31.py. For v3.3 the heading of panel (b) is reworded and both panels are wrapped in \fitbox, as in the paper.
Writes v33/tab_tests.tex. The paper's copy is this file without its first (comment) line.
Run from paper/figs after stats_v3.py:   python make_tabs_v33.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, "v31", "stats_v3.json")))
OUT = os.path.join(HERE, "v33")
MODELS = ("Qwen2.5-0.5B-Instruct", "Qwen2.5-1.5B-Instruct", "SmolLM2-1.7B-Instruct", "Qwen2.5-3B-Instruct")
SHORT = {"Qwen2.5-0.5B-Instruct": "Qwen2.5-0.5B", "Qwen2.5-1.5B-Instruct": "Qwen2.5-1.5B",
         "SmolLM2-1.7B-Instruct": "SmolLM2-1.7B", "Qwen2.5-3B-Instruct": "Qwen2.5-3B (bf16)"}
AL = {"A0_none": "A0", "A1_prompt_rule": "A1", "A2_code_verifier": "A2", "A3_structured_status": "A3"}


def pfmt(p):
    if p is None: return "--"
    if p >= 0.01: return f"{p:.2g}" if p < 0.1 else f"{p:.2f}".rstrip("0").rstrip(".") if p < 1 else "1"
    m, e = f"{p:.1e}".split("e"); return f"${m}\\times10^{{{int(e)}}}$"


def tests():
    L = [r"\begin{tabular}{@{}llrrrrrr@{}}\toprule",
         r"model & $Y$ vs $X$ & pairs & $b$ (only $X$) & $c$ (only $Y$) & $p$ exact & $p$ Holm & $Y-X$, pp [95\% bootstrap] \\ \midrule"]
    for m in MODELS:
        rows = [r for r in S["mcnemar"] if r["model"] == m]
        for i, r in enumerate(rows):
            L.append((SHORT[m] if i == 0 else "") + f" & {AL[r['second']]} vs {AL[r['first']]} & {r['pairs']} & {r['b_first_only']} & {r['c_second_only']} & "
                     + (r"-- & -- & n/a (no discordant pairs) \\" if r['b_first_only'] + r['c_second_only'] == 0 else
                     f"{pfmt(r['p_exact'])} & {pfmt(r['p_holm'])} & ${r['diff_pp']:+.1f}$ [${r['boot_lo']:+.1f}$, ${r['boot_hi']:+.1f}$] \\\\"))
        L.append(r"\addlinespace")
    L[-1] = r"\bottomrule\end{tabular}"
    a = "\n".join(L)
    C = [r"\begin{tabular}{@{}lllll@{}}\toprule",
         r"model & wording condition (8) & option order (W1--W3) & clearance variant (8) & channel (3) \\ \midrule"]
    for m in MODELS:
        c = S["cramer"][m]; cells = []
        for k in ("condition", "order_W1_W3", "variant", "channel"):
            v = c[k]
            cells.append("n/a (no unsafe execution)" if v["V"] is None else f"{v['V']:.2f} ($p$ {pfmt(v['p'])})")
        C.append(SHORT[m] + " & " + " & ".join(cells) + r" \\")
    C.append(r"\bottomrule\end{tabular}")
    s = (r"\small\setlength{\tabcolsep}{4pt}" + "\n(a) Exact McNemar tests on paired non-valid scenarios\\par\\smallskip\n" + a +
         "\n\n\\medskip (b) Cram\\'er's V of unsafe execution with each design factor under \\arm{A0}, using non-valid episodes ($n=384$ overall, $n=288$ for option order)\\par\\smallskip\n" + "\n".join(C) + "\n")
    s = s.replace(r"\begin{tabular}", r"\fitbox{\begin{tabular}").replace(r"\end{tabular}", r"\end{tabular}}")
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "tab_tests.tex"), "w").write("% generated by make_tabs_v33.py -- do not edit\n" + s)
    print("wrote v33/tab_tests.tex")


if __name__ == "__main__":
    tests()
