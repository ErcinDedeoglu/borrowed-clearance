r"""v3.3 related-work comparison (Table 1): the table rows exactly as in v3.2b, read from v32b/positioning_v32b.json
(the per-cell evidence record, unchanged; shipped with the arXiv source as anc/positioning_v32b.json), and the v3.3 legend
(the ten properties as a list, then the three partial entries and the FinVault note), read from v33/tab_positioning_legend.tex.
Writes v33/tab_positioning.tex. The paper's copy is this file without its first (comment) line.
Run from paper/figs:   python3 make_positioning_v33.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
Q = json.load(open(os.path.join(HERE, "v32b", "positioning_v32b.json")))
LEGEND = open(os.path.join(HERE, "v33", "tab_positioning_legend.tex")).read().rstrip("\n")
OUT = os.path.join(HERE, "v33")


def esc(s):
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")


cols = list(Q["columns"].keys())
mark = {"Y": r"\checkmark", "P": r"(\checkmark)", "-": "--", "?": "?"}
L = [r"\begin{tabular}{@{}l" + "c" * len(cols) + r"@{}}\toprule", "evaluation & " + " & ".join(cols) + r" \\ \midrule"]
for r in Q["rows"]:
    name = esc(r["name"]) + (r"$^{\dagger}$" if "status" in r else "") + (f"~\\cite{{{r['key']}}}" if r["key"] else "")
    L.append(name + " & " + " & ".join(mark[r["cells"][c]] for c in cols) + r" \\")
L.append(r"\bottomrule\end{tabular}")
s = r"\small\setlength{\tabcolsep}{5pt}" + "\n" + "\n".join(L) + "\n\n\\smallskip{\\footnotesize " + LEGEND + "}\n"
s = s.replace(r"\begin{tabular}", r"\fitbox{\begin{tabular}").replace(r"\end{tabular}", r"\end{tabular}}")
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, "tab_positioning.tex"), "w").write("% generated by make_positioning_v33.py -- do not edit\n" + s)
print("wrote v33/tab_positioning.tex")
