#!/usr/bin/env python3
r"""Write v33/MANIFEST.json and v33/tab_provenance.tex for the current paper version (v3.3).
v33/MANIFEST.json is v32b/MANIFEST.json with
- the related-evaluations table now written by make_positioning_v33.py to v33/tab_positioning.tex (same rows; v3.3 legend
  from v33/tab_positioning_legend.tex), input J unchanged (v32b/positioning_v32b.json),
- the paired-tests table now written by make_tabs_v33.py to v33/tab_tests.tex (same rows from S; v3.3 panel (b) heading),
- the v33 scripts and the legend file hashed with the other scripts.
v33/tab_provenance.tex is generated from v33/MANIFEST.json in the paper's row order with the v3.3 list of input keys; it is
not listed in itself. The paper's copy of each v33 table is the file without its first (comment) line.
Run from paper/figs after make_manifest_v32b.py, make_positioning_v33.py and make_tabs_v33.py:   python3 manifest_v33.py"""
import json, hashlib, os
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.dirname(os.path.dirname(H))
sha = lambda p: hashlib.sha256(open(os.path.join(R, p), "rb").read()).hexdigest()
m = json.load(open(os.path.join(H, "v32b", "MANIFEST.json")))
NEW = {"Table related evaluations": ("paper/figs/v33/tab_positioning.tex", "make_positioning_v33.py"),
       "Table paired tests": ("paper/figs/v33/tab_tests.tex", "make_tabs_v33.py")}
for a in m["artifacts"]:
    if a["object"] in NEW:
        a["file"], a["scripts"] = NEW[a["object"]]; a["sha256"] = sha(a["file"])
        m["outputs"][a["file"]] = a["sha256"]
assert all(any(a["object"] == o for a in m["artifacts"]) for o in NEW)
# paper row order (Table "provenance"): the related-evaluations table follows the safety-utility figure
ORDER = ["Fig. threat model", "Fig. harness", "Fig. trajectory schematic", "Table main results", "Fig. execution by arm", "Fig. option order",
         "Fig. channel-variant heatmap", "Fig. trajectory decomposition", "Fig. verify-then-ignore by reason", "Table failure modes",
         "Fig. safety against utility", "Table related evaluations", "Fig. pilot", "Table pilot", "Fig. design", "Fig. execution by condition",
         "Fig. execution by variant", "Table per-condition rates", "Table paired tests", "Table channel marginals", "Table run manifests",
         "Table failure-mode examples", "Fig. verbatim trajectories", "Prompts", "Table clearance strings", "Trajectory gallery"]
assert sorted(ORDER) == sorted(a["object"] for a in m["artifacts"]), "artifact list changed"
m["artifacts"].sort(key=lambda a: ORDER.index(a["object"]))
m["outputs"] = dict(sorted(m["outputs"].items()))
for s in ["paper/figs/make_positioning_v33.py", "paper/figs/make_tabs_v33.py", "paper/figs/manifest_v33.py", "paper/figs/v33/tab_positioning_legend.tex"]:
    m["scripts"][s] = sha(s)
m["scripts"] = dict(sorted(m["scripts"].items()))
m["note"] += ("; v3.3: tab_positioning.tex (legend as a list of the ten properties) written by make_positioning_v33.py and tab_tests.tex "
              "(panel (b) heading reworded, panels fitted to the text width) written by make_tabs_v33.py, both to v33/ with the same rows; "
              "v33/tab_provenance.tex written by manifest_v33.py")
json.dump(m, open(os.path.join(H, "v33", "MANIFEST.json"), "w"), indent=1, sort_keys=True)
e = lambda t: t.replace("_", r"\_")
tt = lambda t: r"\texttt{" + e(t) + "}"
L = [r"\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{0.27\textwidth}>{\raggedright\arraybackslash}p{0.27\textwidth}ll@{}}\toprule",
     r"object & file in \texttt{figs/v31/} & script(s) in \texttt{figs/} & inputs & SHA-256 (first 12) \\ \midrule"]
for a in m["artifacts"]:
    L.append(f"{a['object']} & {tt(os.path.basename(a['file']))} & {e(a['scripts']).replace('/', '/' + chr(92) + 'allowbreak{}')} & {a['inputs']} & " + r"\texttt{" + a["sha256"][:12] + r"} \\")
L.append(r"\bottomrule\end{tabular}")
K = {"D": "pre-registration document, frozen 30 October 2026",
     "E": "main-run episode logs, \\texttt{runs/main/*/episodes.jsonl}. Their hashes appear in Table~\\ref{tab:repro}",
     "P": "pilot episode logs, \\texttt{runs/pilot*/episodes.jsonl}", "H": "harness sources in \\texttt{code/bcharness/}",
     "S": "\\texttt{stats\\_v3.json}, written by \\texttt{stats\\_v3.py} from E",
     "X": "\\texttt{exhibits\\_v3.json}, written by \\texttt{make\\_exhibits\\_v3.py} from E and H",
     "J": "\\texttt{positioning\\_v32b.json}, containing per-cell evidence from the cited papers and supplied as ancillary file \\texttt{anc/positioning\\_v32b.json}",
     "R": "pre-registered analysis report, written by \\texttt{factorial.py} from E"}
def short(k):
    v = m["inputs"][k]
    return (", hash prefix " + r"\texttt{" + list(v.values())[0][:12] + "}") if len(v) == 1 else ""
items = "\n".join(f"\\item \\textbf{{{k}:}} {K[k]}{short(k)}." for k in "DEPHSXJR")
open(os.path.join(H, "v33", "tab_provenance.tex"), "w").write("% generated by manifest_v33.py from v33/MANIFEST.json -- do not edit\n"
    r"\footnotesize\setlength{\tabcolsep}{3pt}" + "\n\\fitbox{" + "\n".join(L) + "}\n\n\\smallskip{\\footnotesize The input keys in Table~\\ref{tab:provenance} identify the following files:\n"
    "\\begin{itemize}[leftmargin=*,itemsep=1pt]\n" + items + "\n\\end{itemize}}\n")
print("wrote v33/MANIFEST.json and v33/tab_provenance.tex:", len(m["artifacts"]), "artifacts")
